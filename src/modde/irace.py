"""Export modde's configuration space to irace (D-C10).

irace (https://mlopez-ibanez.github.io/irace/) reads a *parameter file*
describing the space and, optionally, a *configurations file* with initial
configurations. It calls a target runner with the chosen values as
command-line arguments (``--name value ...``); ``config_from_irace`` turns
those back into a ConfigSpace configuration.

Typical use::

    modde.irace.write_irace_files("tuning/", dim=10)   # parameters.txt, configurations.txt
    # in the target runner:
    config = modde.irace.config_from_irace(sys.argv[5:], modde.get_configspace(10))
    opt = modde.ModularDE(problem, budget=..., config=config).run()
"""
from __future__ import annotations

import shlex
from pathlib import Path
from typing import Iterable, Mapping

from ConfigSpace import (AndConjunction, CategoricalHyperparameter, Configuration,
                         ConfigurationSpace, EqualsCondition, InCondition, OrConjunction)
from ConfigSpace.util import deactivate_inactive_hyperparameters

from .configspace import get_configspace, get_presets


def _label(value) -> str:
    """How a categorical value is written for irace (booleans as True/False)."""
    return str(value)


def _quoted(value) -> str:
    return f'"{_label(value)}"'


def _condition(cond) -> str:
    if isinstance(cond, OrConjunction):
        return " || ".join(f"({_condition(c)})" for c in cond.components)
    if isinstance(cond, AndConjunction):
        return " && ".join(f"({_condition(c)})" for c in cond.components)
    parent = cond.parent.name
    if isinstance(cond, InCondition):
        return f"{parent} %in% c({', '.join(_quoted(v) for v in cond.values)})"
    if isinstance(cond, EqualsCondition):
        return f"{parent} == {_quoted(cond.value)}"
    raise TypeError(f"unsupported condition type {type(cond).__name__}")


def irace_parameters(cs: ConfigurationSpace) -> str:
    """The irace parameter file (as text) for a configuration space."""
    conditions = {c.child.name: c for c in cs.conditions}
    width = max(len(hp.name) for hp in cs.values()) + 2
    lines = [
        "## modde configuration space for irace (generated by modde.irace)",
        "## name  switch  type  values  [| condition]",
    ]
    for hp in cs.values():
        if isinstance(hp, CategoricalHyperparameter):
            kind, values = "c", ", ".join(_label(v) for v in hp.choices)
        else:
            base = "i" if type(hp).__name__.endswith("IntegerHyperparameter") else "r"
            kind = f"{base},log" if hp.log else base
            values = f"{hp.lower}, {hp.upper}"
        line = f'{hp.name:<{width}} "--{hp.name} "  {kind:<6} ({values})'
        if hp.name in conditions:
            line += f" | {_condition(conditions[hp.name])}"
        lines.append(line)
    return "\n".join(lines) + "\n"


def irace_configurations(configurations: Mapping[str, Configuration], cs: ConfigurationSpace) -> str:
    """An irace configurations file: one row per configuration, ``NA`` for
    inactive parameters. Row names are written as comments above the table."""
    names = [hp.name for hp in cs.values()]
    lines = ["## initial configurations for irace (generated by modde.irace)"]
    lines += [f"## row {i + 1}: {label}" for i, label in enumerate(configurations)]
    lines.append(" ".join(names))
    for config in configurations.values():
        values = dict(config)
        lines.append(" ".join(_label(values[n]) if n in values else "NA" for n in names))
    return "\n".join(lines) + "\n"


def write_irace_files(directory: str | Path, dim: int, include_presets: bool = True,
                      **configspace_options) -> dict[str, Path]:
    """Write ``parameters.txt`` (and ``configurations.txt`` with the default and,
    optionally, all presets) for a ``dim``-dimensional problem. Extra keyword
    arguments are passed to :func:`modde.get_configspace`."""
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    cs = get_configspace(dim, **configspace_options)
    paths = {"parameters": directory / "parameters.txt"}
    paths["parameters"].write_text(irace_parameters(cs), encoding="utf-8")
    configs = {"default (classic DE)": cs.get_default_configuration()}
    if include_presets:
        configs.update({k: v for k, v in get_presets(dim, cs).items() if k != "DE"})
    paths["configurations"] = directory / "configurations.txt"
    paths["configurations"].write_text(irace_configurations(configs, cs), encoding="utf-8")
    return paths


def config_from_irace(arguments: str | Iterable[str], cs: ConfigurationSpace) -> Configuration:
    """Parse irace's target-runner arguments (``--name value ...`` or ``--name=value``)
    into a configuration of ``cs``. Unknown names raise ``KeyError``."""
    tokens = shlex.split(arguments) if isinstance(arguments, str) else list(arguments)
    values: dict = {}
    i = 0
    while i < len(tokens):
        token = tokens[i]
        if not token.startswith("--"):
            raise ValueError(f"expected '--name', got {token!r}")
        if "=" in token:
            name, raw = token[2:].split("=", 1)
            i += 1
        else:
            name, raw = token[2:], tokens[i + 1]
            i += 2
        hp = cs[name]
        if isinstance(hp, CategoricalHyperparameter):
            matches = [c for c in hp.choices if _label(c) == raw]
            if not matches:
                raise ValueError(f"{name}: {raw!r} is not one of {[_label(c) for c in hp.choices]}")
            values[name] = matches[0]
        elif type(hp).__name__.endswith("IntegerHyperparameter"):
            number = float(raw)
            if not number.is_integer():
                raise ValueError(f"{name}: {raw!r} is not an integer")
            values[name] = int(number)
        else:
            values[name] = float(raw)
    # parameters irace did not pass are inactive; fill defaults, then deactivate
    full = {hp.name: hp.default_value for hp in cs.values()}
    full.update(values)
    config = deactivate_inactive_hyperparameters(full, cs)
    for name, value in values.items():
        if name not in dict(config):
            raise ValueError(f"{name} was given but is inactive in this configuration")
    return config
