"""Generate src/sobol_directions.cpp from the Joe & Kuo direction numbers.

Source: https://web.maths.unsw.edu.au/~fkuo/sobol/new-joe-kuo-6.21201
(BSD-style licence, reproduced in src/modde/_licenses/sobol_joe_kuo.txt).

Usage: python tools/gen_sobol_table.py path/to/new-joe-kuo-6.21201 [max_dim]
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main(path: str, max_dim: int = 1111) -> None:
    rows = []
    with open(path) as fh:
        next(fh)  # header: d s a m_i
        for line in fh:
            parts = line.split()
            d, s, a = int(parts[0]), int(parts[1]), int(parts[2])
            if d > max_dim:
                break
            m = [int(x) for x in parts[3:]]
            assert len(m) == s
            rows.append((d, s, a, m))

    s_vals = ", ".join(str(r[1]) for r in rows)
    a_vals = ", ".join(str(r[2]) for r in rows)
    offsets, flat = [], []
    for r in rows:
        offsets.append(len(flat))
        flat.extend(r[3])

    def wrap(values, per_line=20):
        values = list(values)
        return ",\n    ".join(", ".join(str(v) for v in values[i:i + per_line])
                              for i in range(0, len(values), per_line))

    out = f"""// GENERATED by tools/gen_sobol_table.py -- do not edit by hand.
//
// Sobol direction numbers for dimensions 2..{max_dim} from Joe & Kuo
// (new-joe-kuo-6.21201). Copyright (c) 2008, Frances Y. Kuo and Stephen Joe.
// All rights reserved. Redistributed under the BSD-style licence in
// src/modde/_licenses/sobol_joe_kuo.txt.

#include "modde/sampling.hpp"

namespace modde::sobol
{{
    const int max_dim = {max_dim};

    // Entry j describes dimension j + 2.
    const unsigned short degree[] = {{
    {wrap(s_vals.split(", "))}}};

    const unsigned int polynomial[] = {{
    {wrap(a_vals.split(", "))}}};

    const unsigned int offset[] = {{
    {wrap(offsets)}}};

    const unsigned int initial[] = {{
    {wrap(flat)}}};
}} // namespace modde::sobol
"""
    (ROOT / "src" / "sobol_directions.cpp").write_text(out, encoding="utf-8")
    print(f"wrote {len(rows)} dimensions, {len(flat)} initial direction numbers")


if __name__ == "__main__":
    main(sys.argv[1], int(sys.argv[2]) if len(sys.argv) > 2 else 1111)
